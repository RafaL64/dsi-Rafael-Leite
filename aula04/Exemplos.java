package aula04;

public class Exemplos {
    public static void main(String[] args) {
        int n1 = 10; // variavel inteira 1
        int n2 = 67;// variavel inteira 2
        float decimal = 11.67f; // variavel float
        double paia = 18.6767; // variavel double
        double resultado;// soma de todas as veriáveis
        resultado = n1 + n2 + decimal + paia;
        char caractere = 'a';
        String palavra = "receb";
        System.out.println("A soma de todas as variavei é: " + resultado); // mostra a soma de todas as varivaeis
        System.out.println(palavra + caractere + "!"); // escreve receba

    }
}